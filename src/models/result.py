"""分析流水线各阶段的结构化结果模型（数据字典、执行结果、洞察等）。"""

from typing import Any, Optional

from pydantic import BaseModel, Field


class TableColumn(BaseModel):
    """Table column information."""

    name: str = Field(..., description="Column name")
    data_type: str = Field(..., description="Data type")
    is_nullable: bool = Field(default=True, description="Is nullable")
    description: str = Field(default="", description="Business meaning")
    is_key: bool = Field(default=False, description="Is key field")


class TableInfo(BaseModel):
    """Table information."""

    name: str = Field(..., description="Table name")
    description: str = Field(default="", description="Business meaning")
    columns: list[TableColumn] = Field(default_factory=list, description="Columns")
    row_count: int = Field(default=0, description="Estimated row count")


class TableRelation(BaseModel):
    """Table relationship."""

    from_table: str = Field(..., description="Source table")
    from_column: str = Field(..., description="Source column")
    to_table: str = Field(..., description="Target table")
    to_column: str = Field(..., description="Target column")
    relation_type: str = Field(default="foreign_key", description="Relation type")


class DataDictionary(BaseModel):
    """Data dictionary generated by Data Understanding Agent."""

    tables: list[TableInfo] = Field(default_factory=list, description="Tables")
    relations: list[TableRelation] = Field(default_factory=list, description="Relations")
    key_fields: list[str] = Field(default_factory=list, description="Key business fields")
    summary: str = Field(default="", description="Data overview")


class ExecutionResult(BaseModel):
    """Code execution result."""

    success: bool = Field(..., description="Execution success")
    output: dict[str, Any] = Field(default_factory=dict, description="Execution output")
    logs: str = Field(default="", description="Execution logs")
    error: Optional[str] = Field(default=None, description="Error message")
    duration_ms: int = Field(default=0, description="Execution duration in ms")


class Insight(BaseModel):
    """Business insight."""

    title: str = Field(..., description="Insight title")
    description: str = Field(..., description="Insight description")
    data_support: dict[str, Any] = Field(default_factory=dict, description="Supporting data")
    impact: str = Field(default="", description="Potential impact")
    confidence: float = Field(default=0.8, ge=0.0, le=1.0, description="Confidence score")


class Strategy(BaseModel):
    """Conversion strategy."""

    name: str = Field(..., description="Strategy name")
    target_segment: str = Field(..., description="Target user segment")
    trigger_condition: str = Field(..., description="Trigger condition")
    action: str = Field(..., description="Action to take")
    expected_effect: str = Field(default="", description="Expected effect")
    risk_assessment: str = Field(default="", description="Risk assessment")
    config: dict[str, Any] = Field(default_factory=dict, description="Strategy config")


class AnalysisResult(BaseModel):
    """单次任务端到端产物聚合：编排器逐步填充各字段。"""

    task_id: str = Field(..., description="Task identifier")
    data_dict: Optional[DataDictionary] = Field(default=None, description="Data dictionary")
    analysis_plan: dict[str, Any] = Field(default_factory=dict, description="Analysis plan")
    generated_code: str = Field(default="", description="Generated code")
    execution_result: Optional[ExecutionResult] = Field(default=None, description="Execution result")
    insights: list[Insight] = Field(default_factory=list, description="Generated insights")
    strategies: list[Strategy] = Field(default_factory=list, description="Generated strategies")
